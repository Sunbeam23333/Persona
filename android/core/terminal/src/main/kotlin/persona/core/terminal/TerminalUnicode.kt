package persona.core.terminal

private val graphemePattern = Regex("\\X")
internal fun graphemes(text: String): Sequence<String> = graphemePattern.findAll(text).map { it.value }
internal fun isTerminalNewline(ch: Char): Boolean = ch in "\n\r\u000b\u000c\u0085\u2028\u2029"

internal object TerminalUnicode {
    fun width(character: String): Int {
        if (character.isEmpty()) return 1
        val scalars = character.codePoints().toArray()
        val v = scalars[0]
        if (v < 0x300) return 1
        if (scalars.size == 1 && Character.getType(v) in listOf(Character.NON_SPACING_MARK.toInt(), Character.ENCLOSING_MARK.toInt())) return 0
        if (scalars.any { it == 0xFE0F || it == 0x200D }) return 2
        return if (wide.any { v in it } || emojiPresentation.any { v in it }) 2 else 1
    }

    private val wide = listOf(
        0x1100..0x115F, 0x231A..0x231B, 0x2329..0x232A, 0x2E80..0x303E, 0x3041..0x33FF,
        0x3400..0x4DBF, 0x4E00..0x9FFF, 0xA000..0xA4CF, 0xA960..0xA97F, 0xAC00..0xD7A3,
        0xF900..0xFAFF, 0xFE10..0xFE19, 0xFE30..0xFE6F, 0xFF00..0xFF60, 0xFFE0..0xFFE6,
        0x1F300..0x1F64F, 0x1F900..0x1F9FF, 0x20000..0x2FFFD, 0x30000..0x3FFFD,
    )
    // Default emoji presentation outside the wide ranges above; text symbols stay narrow.
    private val emojiPresentation = listOf(
        0x23E9..0x23EC, 0x23F0..0x23F0, 0x23F3..0x23F3, 0x25FD..0x25FE,
        0x2614..0x2615, 0x2648..0x2653, 0x267F..0x267F, 0x2693..0x2693, 0x26A1..0x26A1,
        0x26AA..0x26AB, 0x26BD..0x26BE, 0x26C4..0x26C5, 0x26CE..0x26CE, 0x26D4..0x26D4,
        0x26EA..0x26EA, 0x26F2..0x26F3, 0x26F5..0x26F5, 0x26FA..0x26FA, 0x26FD..0x26FD,
        0x2705..0x2705, 0x270A..0x270B, 0x2728..0x2728, 0x274C..0x274C, 0x274E..0x274E,
        0x2753..0x2755, 0x2757..0x2757, 0x2795..0x2797, 0x27B0..0x27B0, 0x27BF..0x27BF,
        0x2B1B..0x2B1C, 0x2B50..0x2B50, 0x2B55..0x2B55, 0x1F004..0x1F004, 0x1F0CF..0x1F0CF,
        0x1F18E..0x1F18E, 0x1F191..0x1F19A, 0x1F1E6..0x1F1FF, 0x1F201..0x1F201,
