        0x1F7E0..0x1F7EB, 0x1F7F0..0x1F7F0, 0x1FA70..0x1FA7C, 0x1FA80..0x1FA89,
        0x1FA8F..0x1FAC6, 0x1FACE..0x1FADC, 0x1FADF..0x1FAE9, 0x1FAF0..0x1FAF8,
    )
}
